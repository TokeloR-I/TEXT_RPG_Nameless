#!/usr/bin/env node
/* =========================================================================
 * Enso's Last Stand — ASSET PACKER (Keel's engine decision rev 2, P0)
 * Chrome treats a PNG opened from file:// as another origin, so reading its pixels or uploading it to WebGL
 * (ui/postfx.js) throws SecurityError. Art is therefore shipped inside a script, like assets/sprites/*.js.
 *
 *   node tools/pack-assets.js [srcDir=assets/src] [outFile=assets/packed/assets.js]
 *
 * Every *.png under srcDir becomes ENSO.packedAssets['<path without extension>'] = { type: 'png', w, h, uri }
 * and every Tiled *.json becomes { type: 'tiled', data }. Keys use forward slashes, relative to srcDir
 * (assets/src/tiles/village.png -> 'tiles/village'). Output is sorted, so the file only changes when the art
 * does. Edit the sources and re-run; never edit the output. `npm run pack` runs it, `npm run build` inlines it.
 * ========================================================================= */
const fs = require('fs');
const path = require('path');

const PNG_SIG = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

/** Width and height from a PNG's IHDR chunk; throws on anything that isn't a PNG. */
function pngSize(buf) {
    if (buf.length < 24 || !buf.subarray(0, 8).equals(PNG_SIG) || buf.toString('ascii', 12, 16) !== 'IHDR') throw new Error('not a PNG');
    return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
}

function walk(dir) {
    if (!fs.existsSync(dir)) return [];
    return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
        const p = path.join(dir, e.name);
        return e.isDirectory() ? walk(p) : [p];
    });
}

/** Pack a source folder; returns { source, keys, problems } (pure apart from reading files). */
function pack(srcDir) {
    const entries = [], problems = [];
    for (const file of walk(srcDir).sort()) {
        const ext = path.extname(file).toLowerCase();
        if (ext !== '.png' && ext !== '.json') continue;
        const key = path.relative(srcDir, file).split(path.sep).join('/').replace(/\.[^.]+$/, '');
        try {
            if (ext === '.png') {
                const buf = fs.readFileSync(file);
                const { w, h } = pngSize(buf);
                entries.push([key, `{ type: 'png', w: ${w}, h: ${h}, uri: 'data:image/png;base64,${buf.toString('base64')}' }`]);
            } else {
                const data = JSON.parse(fs.readFileSync(file, 'utf8'));
                entries.push([key, `{ type: 'tiled', data: ${JSON.stringify(data)} }`]);
            }
        } catch (e) { problems.push(`${file}: ${e.message}`); }
    }
    const keys = entries.map(([k]) => k);
    const dupes = keys.filter((k, i) => keys.indexOf(k) !== i);
    for (const k of new Set(dupes)) problems.push(`two source files pack to the same key '${k}' (a .png and a .json with one name?)`);
    const source = [
        '/* GENERATED by tools/pack-assets.js from assets/src. Do not edit: change the art and re-run `npm run pack`. */',
        '(function (global) {',
        '    const ENSO = global.ENSO || (global.ENSO = {});',
        '    const A = ENSO.packedAssets || (ENSO.packedAssets = {});',
        ...entries.map(([k, v]) => `    A[${JSON.stringify(k)}] = ${v};`),
        "})(typeof window !== 'undefined' ? window : globalThis);",
        ''
    ].join('\n');
    return { source, keys, problems };
}

if (require.main === module) {
    const root = path.join(__dirname, '..');
    const src = path.resolve(root, process.argv[2] || 'assets/src');
    const out = path.resolve(root, process.argv[3] || 'assets/packed/assets.js');
    const { source, keys, problems } = pack(src);
    for (const p of problems) console.error('pack-assets:', p);
    if (problems.length) process.exit(1);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, source);
    console.log(`Packed ${keys.length} asset${keys.length === 1 ? '' : 's'} into ${path.relative(root, out)} (${Math.round(source.length / 1024)} KB)`);
}

module.exports = { pack, pngSize };
