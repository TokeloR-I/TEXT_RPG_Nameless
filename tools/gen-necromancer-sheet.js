#!/usr/bin/env node
/* =========================================================================
 * Enso's Last Stand — NECROMANCER TEST SPRITE (PixelLab, 48x48 frames)
 * Wraps assets/art/necromancer/idle-4dir.png (four 48x48 cells: down, up, left, right) into
 * assets/sprites/necromancer-art.js as a data URI, so it also works in the single-file build and from file://.
 *
 *   node tools/gen-necromancer-sheet.js
 *
 * Edit the PNG and re-run; never edit the output.
 * ========================================================================= */
const fs = require('fs');
const path = require('path');
const { pngSize } = require('./pack-assets.js');

const root = path.join(__dirname, '..');
const png = fs.readFileSync(path.join(root, 'assets/art/necromancer/idle-4dir.png'));
const { w, h } = pngSize(png);
if (w !== 192 || h !== 48) throw new Error(`idle-4dir.png must be 192x48 (four 48x48 cells), got ${w}x${h}`);
const blank = JSON.stringify(Array(48).fill('.'.repeat(48)));

const out = `/* GENERATED by tools/gen-necromancer-sheet.js from assets/art/necromancer/idle-4dir.png. Do not edit.
 * Necromancer test sprite (PixelLab), drawn whole: one layer, 48x48 frames, idle only. See docs/SPRITES.md. */
(function (global) {
    const ENSO = global.ENSO || (global.ENSO = {});
    const sheets = ENSO.spriteSheets || (ENSO.spriteSheets = {});
    const manifest = ENSO.spriteManifest || (ENSO.spriteManifest = {});
    const still = (ms) => [{ pose: 'stand', ms, oy: 0 }];
    manifest.necromancer = {
        classes: ['necromancer'],              // player classes drawn with this character instead of manifest.player
        frame: { w: 48, h: 48 },
        anchor: { x: 24, y: 43 },
        animations: {
            idle: [{ pose: 'stand', ms: 520, oy: 0 }, { pose: 'stand', ms: 520, oy: 1 }],
            walk: [{ pose: 'stand', ms: 110, oy: 1 }, { pose: 'stand', ms: 110, oy: 0 }],
            attack: { once: true, then: 'idle', steps: still(500) },
            cast: { once: true, then: 'idle', steps: [{ pose: 'stand', ms: 220, oy: -1 }, { pose: 'stand', ms: 220, oy: 0 }] },
            hit: { once: true, then: 'idle', steps: [{ pose: 'stand', ms: 120, oy: -1 }, { pose: 'stand', ms: 200, oy: 0 }] },
            death: { once: true, steps: [{ pose: 'stand', ms: 160, oy: 1 }, { pose: 'stand', ms: 1, oy: 2 }] }
        },
        layerOrder: { down: ['body'], up: ['body'], left: ['body'], right: ['body'] },
        layers: { body: 'necromancer.body' },
        fallbacks: {}
    };
    sheets['necromancer.body.loading'] = { layer: 'body', frame: { w: 48, h: 48 }, frames: { down: ${blank}, up: { mirror: 'down' }, left: { mirror: 'down' }, right: { mirror: 'down' } } };
    sheets['necromancer.body'] = {
        layer: 'body', frame: { w: 48, h: 48 },
        src: 'data:image/png;base64,${png.toString('base64')}',
        grid: { cols: 4 },
        frames: { down: 0, up: 1, left: 2, right: 3 },
        fallback: 'necromancer.body.loading'
    };
    if (typeof module !== 'undefined' && module.exports) module.exports = sheets;
})(typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(path.join(root, 'assets/sprites/necromancer-art.js'), out);
console.log(`Wrote assets/sprites/necromancer-art.js (${Math.round(out.length / 1024)} KB)`);
